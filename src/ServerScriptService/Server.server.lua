local Players = game:GetService("Players")
local Services = script.Parent.Services
local Remotes = require(Services.Remotes).Create()
local PlayerDataService = require(Services.PlayerDataService)
local MapBuilder = require(Services.MapBuilder)
local EconomyService = require(Services.EconomyService)
local EnemyService = require(Services.EnemyService)
local RunService = require(Services.RunService)
local CombatService = require(Services.CombatService)
local UpgradeService = require(Services.UpgradeService)
local EggService = require(Services.EggService)
local MageService = require(Services.MageService)
local PetService = require(Services.PetService)
local DimensionService = require(Services.DimensionService)
local MeditationService = require(Services.MeditationService)
local SprintService = require(Services.SprintService)

-- Wait for the profile before creating a character so players spawn safely
-- into their shared-hub slot after their data is ready.
Players.CharacterAutoLoads = false
MapBuilder:Start()
EconomyService:Start({ PlayerDataService = PlayerDataService, Remotes = Remotes })
EnemyService:Start({ RunService = RunService, EconomyService = EconomyService, MapBuilder = MapBuilder, Remotes = Remotes })
RunService:Start({ PlayerDataService = PlayerDataService, MapBuilder = MapBuilder, EnemyService = EnemyService, Remotes = Remotes })
CombatService:Start({ PlayerDataService = PlayerDataService, RunService = RunService, EnemyService = EnemyService, Remotes = Remotes })
UpgradeService:Start({ PlayerDataService = PlayerDataService, MapBuilder = MapBuilder, Remotes = Remotes })
PetService:Start({ PlayerDataService = PlayerDataService, Remotes = Remotes })
EggService:Start({ PlayerDataService = PlayerDataService, MapBuilder = MapBuilder, PetService = PetService, Remotes = Remotes })
MageService:Start({ PlayerDataService = PlayerDataService, MapBuilder = MapBuilder, Remotes = Remotes })
DimensionService:Start({ MapBuilder = MapBuilder, RunService = RunService, Remotes = Remotes })
MeditationService:Start({ PlayerDataService = PlayerDataService, MapBuilder = MapBuilder, RunService = RunService, Remotes = Remotes })
SprintService:Start({ Remotes = Remotes })
PlayerDataService:Start()
print("RIFT RUN Archmage corridor server started")
